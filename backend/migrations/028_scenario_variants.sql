-- 028_scenario_variants.sql
-- 同场景变体池（P1-2）：给代表性冲突场景追加 hidden_config.variants。
--
-- 背景：同一患者练到第三遍，学员已经把「患者藏着什么顾虑、什么条件下才松口」背下来，
-- 这个分就不再代表能力（分数通胀）——这比「难度不够」更该防。变体池让同一场景骨架
-- 每次开局换一组隐藏顾虑和披露节奏，背答案就失效了。
--
-- 结构（内嵌 hidden_config，零 schema 迁移）：
--   hidden_config.variants = [ { "hidden": [...], "instructions": "..." }, ... ]
-- 每个变体可选覆盖 hidden（隐藏顾虑组）与 instructions（披露节奏）；未写的字段沿用主值。
-- 后端按 session_id 用 FNV-1a 确定性选一组：同一会话每轮重算一致、不同会话看到不同变体。
--
-- 设计约束（沿用 020 的判据）：
--   1) 每组 hidden 仍是三条且性质错开（情绪型怕什么 / 证据型握着什么 / 意愿型什么条件下配合）。
--   2) 每组 instructions 仍是「若客服……应……；只有客服……才……」的可判定披露门，
--      并保留 018 的「答非所问」升级规则。
--   3) 只换顾虑与节奏，场景骨架（表面诉求 / 初始情绪 / 合规红线）不变。
--
-- 用 jsonb `||` 追加 variants 键，不覆盖原有 hidden_config 字段。幂等：重复执行写入同值。
-- ⚠️ 与 024/026/027 同性质：将来主管端支持编辑变体后**不要再重跑本迁移**（会覆盖主管改过的值）。

