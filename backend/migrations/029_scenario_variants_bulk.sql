-- 029_scenario_variants_bulk.sql
-- 把变体池铺到其余 8 条上架场景（028 已覆盖 refund-demand / guarantee-demand）。
--
-- 为什么值得铺：变体对付的是**分数通胀**——同一患者练到第三次，学员已经把「他藏着什么顾虑、
-- 什么条件下才松口」背下来了，这个分就不再代表能力。存量 10 条场景里只有 2 条有变体，
-- 其余 8 条复练必然通胀；而冲突类（投诉/逼承诺/比价）恰恰是复练率最高的那几类。
--
-- 沿用 028 的结构与约束（不改骨架、不动开场白、不影响合规红线）：
--   hidden_config.variants = [ { "hidden": [...], "instructions": "..." }, ... ]
--   * 每组 hidden 仍按「情绪型（怕什么）/ 证据型（握着什么）/ 意愿型（什么条件下配合）」错开；
--   * 每组 instructions 与主值同一风格：basic 场景是「追问规则」，advanced 场景带「只有……才……」披露门；
--   * 只换顾虑组合与披露节奏，表面诉求、初始情绪、服务要点一律不动（那些是场景骨架）。
--
-- 幂等：jsonb `||` 追加/覆盖 variants 键，重复执行写入同值。
-- ⚠️ 与 024/026/027/028 同性质：将来主管端支持编辑变体后**不要再重跑本迁移**。

